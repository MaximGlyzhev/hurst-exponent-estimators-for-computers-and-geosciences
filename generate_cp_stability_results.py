"""Generate data for the CP stability analyses in the accompanying paper.

The program evaluates three profile modifications: additive height noise,
lateral sampling-position errors, and finite height-scale bit depth. Missing-
data (gap) experiments are deliberately excluded and should be generated by a
separate program.

The default experiment follows the manuscript: H = 0.1, ..., 0.9,
L = 100, 500, 2000, tau = 3, and 10,000 profiles per configuration. Results
are written as one summary row per configuration. Use ``--n-profiles`` for a
smaller reproducibility or smoke-test run.

References
----------
Gutjahr, T., Hale, S., Keller, K., Blum, P., & Winter, S. (2022).
Quantification of fracture roughness by change probabilities and Hurst
exponents. Mathematical Geosciences, 54, 679--710.
https://doi.org/10.1007/s11004-021-09985-3

Dietrich, C. R., & Newsam, G. N. (1997). Fast and exact simulation of
stationary Gaussian processes through circulant embedding of the covariance
matrix. SIAM Journal on Scientific Computing, 18, 1088--1107.
https://doi.org/10.1137/S1064827592240555
"""

from __future__ import annotations

import argparse
import csv
import json
import platform
import time
from pathlib import Path
from typing import Iterable

import numpy as np
from CP import estimate_hurst_cp
from Profile_n_bit_conversion import quantize_profile_nbit
from fBm_circulant_embedding import circulant_fBm
from fBm_with_displacements import (
    fBm_with_displacements,
    sigma_from_no_displacement_probability,
)
from fBm_with_white_noise import add_white_noise


DEFAULT_H_VALUES = tuple(round(value, 1) for value in np.arange(0.1, 1.0, 0.1))
DEFAULT_L_VALUES = (100, 500, 2000)
DEFAULT_NOISE_CASES = (
    (0.0125, 2.955, "laboratory"),
    (0.220, 25.296, "field"),
)
DEFAULT_P0_VALUES = (0.9, 0.5, 0.2)
DEFAULT_BIT_DEPTHS = (32, 16, 8)
DEFAULT_TESTS = ("height_noise", "x_displacement", "bit_depth")


def calibrate_c_fbm_for_mean_amplitude(
    H: float,
    L: int,
    target_mean_amplitude: float,
    n_calibration_profiles: int,
    rng: np.random.Generator,
) -> tuple[float, float]:
    """Calibrate ``c_fBm`` to a target mean profile amplitude.

    Unit-topothesy profiles are simulated on the same grid as the stability
    experiment. Since fBm amplitudes scale with ``sqrt(c_fBm)``, the required
    topothesy follows directly from the simulated mean range.

    Returns
    -------
    c_fBm, unit_mean_amplitude : tuple of float
        Calibrated topothesy and Monte Carlo estimate of the mean range for
        unit topothesy.
    """
    if n_calibration_profiles < 2:
        raise ValueError("n_calibration_profiles must be at least 2.")
    ranges: list[float] = []
    while len(ranges) < n_calibration_profiles:
        _, first, second = circulant_fBm(
            H=H, L=L, x_max=float(L - 1), c_fBm=1.0, rng=rng
        )
        ranges.append(float(np.ptp(first)))
        if len(ranges) < n_calibration_profiles:
            ranges.append(float(np.ptp(second)))
    unit_mean_amplitude = float(np.mean(ranges))
    c_fBm = (target_mean_amplitude / unit_mean_amplitude) ** 2
    return float(c_fBm), unit_mean_amplitude


def _summary_row(
    estimates: Iterable[float],
    *,
    test: str,
    H: float,
    L: int,
    tau: int,
    n_profiles: int,
    seed: int,
    elapsed_seconds: float,
    parameters: dict[str, object],
) -> dict[str, object]:
    values = np.asarray(list(estimates), dtype=float)
    if values.size != n_profiles or not np.all(np.isfinite(values)):
        raise RuntimeError("The simulation produced invalid CP estimates.")
    mean_estimate = float(np.mean(values))
    centred = values - mean_estimate
    return {
        "test": test,
        "H": H,
        "L": L,
        "tau": tau,
        "n_profiles": n_profiles,
        "mean_estimate": mean_estimate,
        "signed_estimation_error": mean_estimate - H,
        "absolute_estimation_error": abs(mean_estimate - H),
        "mean_absolute_profile_error": float(np.mean(np.abs(values - H))),
        "standard_deviation": float(np.std(values, ddof=1)),
        "absolute_third_central_moment": float(np.mean(np.abs(centred) ** 3)),
        "seed": seed,
        "elapsed_seconds": elapsed_seconds,
        **parameters,
    }


def generate_cp_stability_results(
    *,
    H_values: Iterable[float] = DEFAULT_H_VALUES,
    L_values: Iterable[int] = DEFAULT_L_VALUES,
    n_profiles: int = 10_000,
    tau: int = 3,
    tests: Iterable[str] = DEFAULT_TESTS,
    n_calibration_profiles: int = 2_000,
    seed: int = 20260827,
) -> list[dict[str, object]]:
    """Generate summary statistics for the three CP stability tests.

    Parameters use the notation of the manuscript. Independent deterministic
    random streams are assigned to every configuration. Height-noise
    topothesies are calibrated for each ``(H, L, target amplitude)`` because
    the finite-grid mean range also depends weakly on ``L``.

    Returns
    -------
    list of dict
        One row per modification, ``H``, and ``L`` configuration.
    """
    if n_profiles < 2:
        raise ValueError("n_profiles must be at least 2.")
    allowed_tests = set(DEFAULT_TESTS)
    selected_tests = tuple(tests)
    unknown = set(selected_tests) - allowed_tests
    if unknown:
        raise ValueError(f"Unknown tests: {sorted(unknown)}")

    H_values = tuple(float(value) for value in H_values)
    L_values = tuple(int(value) for value in L_values)
    seed_sequence = np.random.SeedSequence(seed)
    rows: list[dict[str, object]] = []

    configurations: list[tuple[str, float, int, dict[str, object]]] = []
    for H in H_values:
        for L in L_values:
            if "height_noise" in selected_tests:
                for intensity, amplitude, source in DEFAULT_NOISE_CASES:
                    configurations.append(("height_noise", H, L, {
                        "noise_intensity_I": intensity,
                        "target_mean_amplitude": amplitude,
                        "noise_case": source,
                    }))
            if "x_displacement" in selected_tests:
                for p0 in DEFAULT_P0_VALUES:
                    configurations.append(("x_displacement", H, L, {"p0": p0}))
            if "bit_depth" in selected_tests:
                for n_bits in DEFAULT_BIT_DEPTHS:
                    configurations.append(("bit_depth", H, L, {"n_bits": n_bits}))

    child_seeds = seed_sequence.spawn(len(configurations))
    for index, ((test, H, L, parameters), child_seed) in enumerate(
        zip(configurations, child_seeds), start=1
    ):
        configuration_seed = int(child_seed.generate_state(1, dtype=np.uint64)[0])
        rng = np.random.default_rng(configuration_seed)
        estimates: list[float] = []
        start = time.perf_counter()

        if test == "height_noise":
            target = float(parameters["target_mean_amplitude"])
            c_fBm, unit_amplitude = calibrate_c_fbm_for_mean_amplitude(
                H, L, target, n_calibration_profiles, rng
            )
            parameters.update({
                "c_fBm": c_fBm,
                "calibration_unit_mean_amplitude": unit_amplitude,
                "n_calibration_profiles": n_calibration_profiles,
            })
            intensity = float(parameters["noise_intensity_I"])
            while len(estimates) < n_profiles:
                _, first, second = circulant_fBm(
                    H, L, float(L - 1), c_fBm=c_fBm, rng=rng
                )
                for profile in (first, second):
                    observed = add_white_noise(profile, I=intensity, rng=rng)
                    estimates.append(estimate_hurst_cp(observed, tau=tau))
                    if len(estimates) == n_profiles:
                        break

        elif test == "x_displacement":
            m = 4
            d = 1.0
            p0 = float(parameters["p0"])
            sigma = sigma_from_no_displacement_probability(p0, m=m, d=d)
            parameters.update({"m": m, "d": d, "sigma": sigma, "c_fBm": 1.0})
            for _ in range(n_profiles):
                _, profile = fBm_with_displacements(
                    H, L, float(L - 1), 1.0, m, sigma, rng=rng
                )
                estimates.append(estimate_hurst_cp(profile, tau=tau))

        else:
            n_bits = int(parameters["n_bits"])
            parameters.update({"c_fBm": 1.0})
            while len(estimates) < n_profiles:
                _, first, second = circulant_fBm(
                    H, L, float(L - 1), c_fBm=1.0, rng=rng
                )
                for profile in (first, second):
                    quantized, _ = quantize_profile_nbit(profile, n_bits)
                    estimates.append(estimate_hurst_cp(quantized, tau=tau))
                    if len(estimates) == n_profiles:
                        break

        elapsed = time.perf_counter() - start
        rows.append(_summary_row(
            estimates,
            test=test,
            H=H,
            L=L,
            tau=tau,
            n_profiles=n_profiles,
            seed=configuration_seed,
            elapsed_seconds=elapsed,
            parameters=parameters,
        ))
        print(
            f"[{index:3d}/{len(configurations)}] {test:14s} "
            f"H={H:.1f}, L={L}: {elapsed:.2f} s",
            flush=True,
        )
    return rows


def write_results(rows: list[dict[str, object]], output: Path, metadata: dict) -> None:
    """Write a rectangular CSV file and a JSON metadata sidecar."""
    output.parent.mkdir(parents=True, exist_ok=True)
    preferred = [
        "test", "H", "L", "tau", "n_profiles", "mean_estimate",
        "signed_estimation_error", "absolute_estimation_error",
        "mean_absolute_profile_error",
        "standard_deviation", "absolute_third_central_moment",
    ]
    all_keys = {key for row in rows for key in row}
    fieldnames = preferred + sorted(all_keys - set(preferred))
    with output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    metadata_path = output.with_suffix(".metadata.json")
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("cp_stability_results.csv"))
    parser.add_argument("--n-profiles", type=int, default=10_000)
    parser.add_argument("--n-calibration-profiles", type=int, default=2_000)
    parser.add_argument("--tau", type=int, default=3)
    parser.add_argument("--seed", type=int, default=20260827)
    parser.add_argument(
        "--tests", nargs="+", choices=DEFAULT_TESTS, default=list(DEFAULT_TESTS)
    )
    return parser.parse_args()


def main() -> None:
    """Run the command-line data-generation workflow."""
    args = _parse_args()
    total_start = time.perf_counter()
    rows = generate_cp_stability_results(
        n_profiles=args.n_profiles,
        tau=args.tau,
        tests=args.tests,
        n_calibration_profiles=args.n_calibration_profiles,
        seed=args.seed,
    )
    total_elapsed = time.perf_counter() - total_start
    metadata = {
        "purpose": "CP stability tests without missing-data/gap tests",
        "tests": args.tests,
        "H_values": DEFAULT_H_VALUES,
        "L_values": DEFAULT_L_VALUES,
        "n_profiles": args.n_profiles,
        "tau": args.tau,
        "n_calibration_profiles": args.n_calibration_profiles,
        "seed": args.seed,
        "total_elapsed_seconds": total_elapsed,
        "python": platform.python_version(),
        "numpy": np.__version__,
        "platform": platform.platform(),
    }
    write_results(rows, args.output, metadata)
    print(f"Wrote {len(rows)} rows to {args.output}")
    print(f"Total runtime: {total_elapsed:.2f} s")


if __name__ == "__main__":
    main()
